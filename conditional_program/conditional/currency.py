# 16. Currency Converter

print("1.USD to INR  2.EUR to INR  3.GBP to INR")

choice = int(input("Enter choice: "))
amount = float(input("Enter amount: "))

if choice == 1:
    print("INR =", amount * 83)
elif choice == 2:
    print("INR =", amount * 90)
elif choice == 3:
    print("INR =", amount * 100)
else:
    print("Invalid Choice")























    